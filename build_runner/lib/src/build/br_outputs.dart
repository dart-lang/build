import 'package:build/build.dart';
import 'package:path/path.dart' as p;

const String _br = '_br_';
const String _dartExtension = '.dart';
const String _partDartExtension = '.part.dart';

/// The reserved `_br_` directory namespace.
///
/// `build_runner` manages internal outputs under this namespace. Files under
/// `lib/` correspond to outputs under `lib/_br_/`, while files outside `lib/`
/// correspond to outputs under `_br_/` at the package root.
///
/// Currently this namespace is used for shared part files generated by the
/// "Add to Library" feature, which use the `.part.dart` extension. For more
/// details, see `docs/writing_builders.md`.
extension AssetIdBrOutputsExtension on AssetId {
  /// Whether this is an output in the `_br_` namespace.
  bool get isBrOutput {
    final segments = pathSegments;
    return segments.first == _br ||
        (segments.length >= 2 && segments[0] == 'lib' && segments[1] == _br);
  }

  /// Whether this `_br_` output represents a shared part generated by
  /// `build_runner`.
  bool get isBrSharedPart => isBrOutput && path.endsWith(_partDartExtension);

  /// The corresponding shared part `.part.dart` AssetId if this is a Dart
  /// library outside the `_br_` namespace.
  AssetId? get sharedPartId {
    if (!path.endsWith(_dartExtension) || isBrOutput) return null;
    final segments = pathSegments;
    final filenameWithoutDart = segments.last.substring(
      0,
      segments.last.length - _dartExtension.length,
    );
    final partFilename = '$filenameWithoutDart$_partDartExtension';
    final isLib = segments.first == 'lib';
    final newSegments = isLib
        ? [
            'lib',
            _br,
            ...segments.sublist(1, segments.length - 1),
            partFilename,
          ]
        : [_br, ...segments.sublist(0, segments.length - 1), partFilename];
    return AssetId(package, p.posix.joinAll(newSegments));
  }

  /// The corresponding library `.dart` AssetId if this is a generated shared
  /// part.
  AssetId? get sharedPartLibraryId {
    if (!isBrSharedPart) return null;
    final segments = pathSegments;
    final filenameWithoutPartDart = segments.last.substring(
      0,
      segments.last.length - _partDartExtension.length,
    );
    final libraryFilename = '$filenameWithoutPartDart$_dartExtension';
    final isLib = segments.first == 'lib';
    final newSegments = isLib
        ? ['lib', ...segments.sublist(2, segments.length - 1), libraryFilename]
        : [...segments.sublist(1, segments.length - 1), libraryFilename];
    return AssetId(package, p.posix.joinAll(newSegments));
  }
}
