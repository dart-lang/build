import 'package:build/build.dart';

extension AssetIdBrOutputsExtension on AssetId {
  /// Whether this is an output in the `_br_` namespace.
  bool get isBrOutput =>
      path.startsWith('lib/_br_/') || path.startsWith('_br_/');

  /// Whether this is a regular asset, not in the `_br_` namespace.
  bool get isRegularAsset => !isBrOutput;

  /// Whether this `_br_` output represents a shared part generated by
  /// `build_runner`.
  bool get isBrSharedPart => isBrOutput && path.endsWith('.dart');

  /// Returns the corresponding `_br_/` AssetId for a shared part.
  AssetId get sharedPartIdForPrimaryInput {
    final firstSlash = path.indexOf('/');
    if (firstSlash == -1) return AssetId(package, '_br_/$path');

    final topLevelDir = path.substring(0, firstSlash);
    if (topLevelDir == 'lib') {
      final rest = path.substring(firstSlash + 1);
      return AssetId(package, 'lib/_br_/$rest');
    }
    return AssetId(package, '_br_/$path');
  }

  /// Returns the corresponding primary `.dart` AssetId if this is a generated
  /// shared part.
  AssetId? get primaryInputForSharedPartId {
    if (!isBrSharedPart) return null;
    if (path.startsWith('lib/_br_/')) {
      return AssetId(package, 'lib/${path.substring(9)}');
    }
    if (path.startsWith('_br_/')) {
      return AssetId(package, path.substring(5));
    }
    return null;
  }
}
